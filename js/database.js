/* Получить курс */

GroundDB.getCourse =
  function (grade) {

    return GroundDB[
      String(grade)
    ] || null;

  };


/* Получить все уроки класса */

GroundDB.getLessons =
  function (grade) {

    const course =
      GroundDB.getCourse(
        grade
      );

    if (!course) {
      return [];
    }

    return course.lessons;

  };


/* Получить конкретный урок */

GroundDB.getLesson =
  function (grade, lessonId) {

    const lessons =
      GroundDB.getLessons(
        grade
      );

    return lessons.find(
      lesson =>
        lesson.id ===
        Number(lessonId)
    ) || null;

  };


